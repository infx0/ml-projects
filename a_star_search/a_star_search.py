def display_emoji_grid(emoji_grid):
    """
    Display a List of Lists of emojis in a perfect grid (table) in a Jupyter Notebook.
    
    Parameters:
    emoji_grid (list of list of str): A 2D list containing emojis to display in a grid.
    """
    # Create HTML table
    html = '<table style="border-collapse: collapse;">'
    
    for row in emoji_grid:
        html += '<tr>'
        for emoji in row:
            html += f'<td style="border: none; padding: 0px; text-align: center; font-size: 1em;">{emoji}</td>'
        html += '</tr>'
    
    html += '</table>'
    
    # Display the HTML table
    display_html(html, raw=True)

def off_world(position: tuple[int, int], world: List[List[str]]) -> bool:
    """
    a helper function to determine if a child node would be off the edges of the provided world. Works for any rectangular world. Note the input position should be given as (y, x) (i.e. (vertical, horizontal)) in order to display properly
    """
    are_we_off = False
    vert_lim = len(world) - 1
    horiz_lim = len(world[1]) - 1
    if position[0] < 0 or position[1] < 0:
        are_we_off = True
    elif position[0] > vert_lim:
        are_we_off = True
    elif position[1] > horiz_lim:
        are_we_off = True
    return are_we_off

def get_terrain(position: tuple[int, int], world: List[List[str]]) -> str:
    """
    a helper function that retrieves the terrain from the given world and position.  Note the input position should be given as (y, x) (i.e. (vertical, horizontal)) in order to display properly
    """
    return world[position[0]][position[1]]